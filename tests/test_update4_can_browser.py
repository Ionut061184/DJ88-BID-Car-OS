from pathlib import Path
from playwright.sync_api import sync_playwright

assets = Path(__file__).resolve().parents[1] / "app/src/main/assets"
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True,args=["--no-sandbox"])
    page=browser.new_page(viewport={"width":1280,"height":720})
    page.add_init_script("""window.sample={};window.calls=[];window.BID={qfVehicleSnapshot:()=>JSON.stringify(window.sample),open:x=>calls.push(x)};""")
    page.goto((assets/"index.html").as_uri())
    page.wait_for_selector("#qfSpeedTile")
    assert "— km/h" in page.locator("#qfSpeedTile").inner_text()
    assert "— L" in page.locator("#qfSpeedTile").inner_text()
    for id,x1,x2 in [("qfSpeedTile",17,195),("qfFuelTile",1084,1274)]:
        box=page.locator("#"+id).bounding_box()
        assert box and box["x"]>=x1 and box["x"]+box["width"]<=x2 and box["y"]>=625 and box["y"]+box["height"]<=700, box
    page.evaluate("window.sample={fresh:true,ageMs:100,speedCandidate:0,fuelCandidate:18,rpmCandidate:828,messages:2,candidateFrames:1}")
    page.wait_for_function("document.querySelector('#qfSpeedTile').textContent.includes('18.0 L')")
    assert "0 km/h" in page.locator("#qfSpeedTile").inner_text()
    assert "CAN TEST" in page.locator("#qfSpeedTile").inner_text()
    assert page.locator("#qfSpeedTile .qfRow").count()==3
    assert page.locator("#qfFuelTile .qfRow").count()==4
    assert "18.0 L" not in page.locator("#qfFuelTile").inner_text()
    page.evaluate("Object.assign(window.sample,{odometerCandidate:378688,parkingBrakeCandidate:true,washerFlagCandidate:true,outsideTemperatureCandidate:4.5,outsideTemperatureFresh:true,outsideTemperatureAgeMs:100,verified:false})")
    page.wait_for_function("document.querySelector('#qfFuelTile').textContent.includes('378688 km')")
    assert "Frână: —" in page.locator("#qfFuelTile").inner_text()
    page.evaluate("window.sample.verified=true")
    page.wait_for_function("document.querySelector('#qfFuelTile .qfRow:nth-child(2)').dataset.tone==='red'")
    assert page.locator("#qfFuelTile .qfRow:nth-child(4)").get_attribute("data-tone")=="yellow"
    page.evaluate("Object.assign(window.sample,{parkingBrakeCandidate:false,washerFlagCandidate:false})")
    page.wait_for_function("document.querySelector('#qfFuelTile .qfRow:nth-child(2)').dataset.tone==='normal'")
    assert page.locator("#qfFuelTile .qfRow:nth-child(4)").get_attribute("data-tone")=="normal"
    page.evaluate("window.sample.verified=false")
    page.wait_for_function("document.querySelector('#qfFuelTile .qfRow:nth-child(2)').dataset.tone==='unknown'")

    car=page.locator('button[aria-label="Mașină"]')
    assert car.count()==1, "Original car menu button missing"
    car.click()
    assert page.evaluate("calls.includes('car')"), "Original Mașină action no longer opens OEM menu"
    assert not page.locator("#qfVehiclePanel").is_visible()
    page.evaluate("window.calls=[]")
    page.locator("#qfSpeedTile").click()
    assert page.locator("#qfVehiclePanel").is_visible()
    assert "828 RPM" in page.locator("#qfVehicleText").inner_text()
    page.locator("#qfAudit").click()
    assert "lipsește" in page.locator("#qfAuditStatus").inner_text()
    page.evaluate("window.BID.qfBeginBodyAudit=()=>calls.push('audit')")
    page.locator("#qfAudit").click()
    assert page.evaluate("calls.includes('audit')")
    assert "Solicitare trimisă" in page.locator("#qfAuditStatus").inner_text()
    assert page.locator("#qfAudit").is_disabled()
    page.evaluate("Object.assign(window.sample,{listening:true,auditStarted:true,auditActive:true,auditRemainingSeconds:110,auditBeforeMessages:1,auditBeforeValid:0,auditAwayMessages:3,auditAwayValid:2,auditAfterMessages:4,auditAfterValid:1})")
    page.wait_for_function("document.querySelector('#qfAuditStatus').textContent.includes('Test activ: 110 s')")
    page.wait_for_function("document.querySelector('#qfVehicleText').textContent.includes('cât BID nu era în prim-plan: 3 / 2')")

    page.evaluate("Object.assign(window.sample,{radarFresh:true,radarAgeMs:100,radarLevelsCandidate:[null,3,...Array(18).fill(null)],steeringFresh:true,steeringAgeMs:100,steeringRawCandidate:-42,reverseFresh:true,reverseAgeMs:100,reverseEventCandidate:true})")
    page.wait_for_function("document.querySelector('#qfVehicleText').textContent.includes('Radar (niveluri brute, candidat): — / 3')")
    assert "nu grade): -42" in page.locator("#qfVehicleText").inner_text()
    assert "Ultimul eveniment marșarier: START" in page.locator("#qfVehicleText").inner_text()
    page.evaluate("window.sample.radarAgeMs=5001;window.sample.steeringAgeMs=5001;window.sample.reverseAgeMs=5001")
    page.wait_for_function("document.querySelector('#qfVehicleText').textContent.includes('Ultimul eveniment marșarier: —')")
    assert "nu grade): —" in page.locator("#qfVehicleText").inner_text()
    page.evaluate("Object.assign(window.sample,{climateFresh:true,climateAgeMs:100,climateLeft:'LO',climateRight:'21.5',doorFresh:true,doorAgeMs:100,doorMaskCandidate:132})")
    page.wait_for_function("document.querySelector('#qfVehicleText').textContent.includes('LO / 21.5')")
    assert "față stânga: deschis" in page.locator("#qfVehicleText").inner_text()
    assert "capotă: deschis" in page.locator("#qfVehicleText").inner_text()
    page.evaluate("window.sample.doorAgeMs=30001;window.sample.climateAgeMs=30001")
    page.wait_for_function("document.querySelector('#qfVehicleText').textContent.includes('Uși și capace (candidat): —')")
    assert "neconfirmată): — / —" in page.locator("#qfVehicleText").inner_text()
    page.evaluate("Object.assign(window.sample,{outsideTemperatureCandidate:-2.5,outsideTemperatureFresh:true,outsideTemperatureAgeMs:100,temperatureMessages:1})")
    page.wait_for_function("document.querySelector('#qfVehicleText').textContent.includes('-2.5 °C')")
    page.evaluate("window.sample.outsideTemperatureAgeMs=120001")
    page.wait_for_function("document.querySelector('#qfVehicleText').textContent.includes('Temperatură exterioară OEM (candidat): — °C')")
    page.evaluate("Object.assign(window.sample,{parkingBrakeCandidate:true,driverBeltUnfastenedCandidate:false,washerFlagCandidate:true})")
    page.wait_for_function("document.querySelector('#qfVehicleText').textContent.includes('Frână de mână (candidat): activă')")
    assert "Centură șofer (candidat): cuplată" in page.locator("#qfVehicleText").inner_text()
    assert "sens de verificat): 1" in page.locator("#qfVehicleText").inner_text()
    page.evaluate("window.sample={listening:true,messages:2,candidateFrames:1,emptyBody:1,lastPacketState:'empty_body',fresh:false}")
    page.wait_for_function("document.querySelector('#qfVehicleText').textContent.includes('fără informații utile')")
    assert "Frână de mână (candidat): —" in page.locator("#qfVehicleText").inner_text()
    assert "— km/h" in page.locator("#qfSpeedTile").inner_text()
    page.evaluate("window.sample={listening:true,messages:0,candidateFrames:0}")
    page.wait_for_function("document.querySelector('#qfVehicleText').textContent.includes('Niciun mesaj OEM primit')")
    page.evaluate("window.sample={listening:true,messages:0,bodyShareState:'absent',bodySharePackage:'ro.dj88bid.car.update5test'}")
    page.wait_for_function("document.querySelector('#qfVehicleText').textContent.includes('cheie OEM absentă')")
    assert "ro.dj88bid.car.update5test" in page.locator("#qfVehicleText").inner_text()
    page.evaluate("window.sample.bodyRegistryState='not_listed'")
    page.wait_for_function("document.querySelector('#qfVehicleText').textContent.includes('BID nu este înregistrat')")
    page.evaluate("window.sample.bodyRegistryState='listed'")
    page.wait_for_function("document.querySelector('#qfVehicleText').textContent.includes('BID înregistrat')")
    page.evaluate("window.sample.bodyShareState='enabled'")
    page.wait_for_function("document.querySelector('#qfVehicleText').textContent.includes('activată în setări')")
    assert "— km/h" in page.locator("#qfSpeedTile").inner_text()
    page.evaluate("window.sample.bodyShareState='unreadable'")
    page.wait_for_function("document.querySelector('#qfVehicleText').textContent.includes('nu poate fi citită')")
    page.evaluate("window.sample={listening:true,messages:3,candidateFrames:0,lastSize:64,wrongLength:3}")
    page.wait_for_function("document.querySelector('#qfVehicleText').textContent.includes('64 octeți')")
    assert "formatul nu corespunde" in page.locator("#qfVehicleText").inner_text()
    assert "Lungime: 3" in page.locator("#qfVehicleText").inner_text()
    assert "— km/h" in page.locator("#qfSpeedTile").inner_text()
    page.evaluate("window.sample={listening:false,registrationError:'SecurityException'}")
    page.wait_for_function("document.querySelector('#qfVehicleText').textContent.includes('SecurityException')")
    page.evaluate("window.sample={listening:true,fresh:true,ageMs:100,speedCandidate:0,fuelCandidate:18,rpmCandidate:828,messages:2,candidateFrames:1}")
    page.wait_for_function("document.querySelector('#qfSpeedTile').textContent.includes('18.0 L')")
    page.locator("#qfOriginal").click()
    assert page.evaluate("calls.includes('car')")
    page.evaluate("window.calls=[]")
    page.locator("#qfSpeedTile").click()
    page.locator("#qfBodyOriginal").click()
    assert page.evaluate("calls.includes('canbus')")
    assert not page.locator("#qfVehiclePanel").is_visible()
    page.evaluate("window.sample.ageMs=6000")
    page.wait_for_function("document.querySelector('#qfSpeedTile').textContent.includes('— L')")
    page.evaluate("window.sample={fresh:true,ageMs:100,speedCandidate:999,fuelCandidate:-1}")
    page.wait_for_timeout(1200)
    assert "— km/h" in page.locator("#qfSpeedTile").inner_text()
    assert "— L" in page.locator("#qfSpeedTile").inner_text()
    browser.close()
print("PASS: CAN test tile geometry, original menu, valid zero, invalid and stale data")
