from pathlib import Path
from playwright.sync_api import sync_playwright
assets=Path("app/src/main/assets").resolve()
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,args=["--no-sandbox"])
    page=browser.new_page(viewport={"width":1280,"height":720})
    page.add_init_script("""window.pin='';window.calls=[];window.BID={open:x=>calls.push(x),settingsPinEnabled:()=>!!pin,settingsPinVerify:x=>x===pin?'ok':'wrong',settingsPinChange:(o,n)=>{if(pin&&pin!==o)return 'wrong';pin=n;return 'ok'}};""")
    page.goto((assets/"index.html").as_uri())
    page.evaluate("bidSystemOpen()")
    assert "Dezactivat" in page.locator("#bidSecurityOpen").inner_text()
    page.locator("#bidSecurityOpen").click()
    page.locator("#bidNewPin").fill("123456")
    page.locator("#bidConfirmPin").fill("123456")
    page.locator("#bidSecuritySave").click()
    assert "Activ" in page.locator("#bidSecurityOpen").inner_text()
    waze=page.locator('[data-favorite="waze"]')
    before=waze.get_attribute("aria-pressed")
    waze.click()
    page.locator("#bidOldPin").fill("999999")
    page.locator("#bidSecuritySave").click()
    assert "incorect" in page.locator("#bidSecurityStatus").inner_text()
    assert waze.get_attribute("aria-pressed")==before
    page.locator("#bidOldPin").fill("123456")
    page.locator("#bidSecuritySave").click()
    assert waze.get_attribute("aria-pressed")!=before
    page.locator("#bidSystemOEM").click()
    assert page.evaluate("calls.at(-1)")=="original"
    page.evaluate("bidSystemOpen()")
    page.locator("#bidSecurityOpen").click()
    page.locator("#bidOldPin").fill("123456")
    page.locator("#bidNewPin").fill("654321")
    page.locator("#bidConfirmPin").fill("654321")
    page.locator("#bidSecuritySave").click()
    page.locator("#bidSecurityOpen").click()
    page.locator("#bidOldPin").fill("654321")
    page.locator("#bidSecurityDisable").click()
    assert "Dezactivat" in page.locator("#bidSecurityOpen").inner_text()
    waze.click()
    assert not page.locator("#bidSecurityPanel").is_visible()
    browser.close()
print("PASS: optional PIN UI, wrong PIN, preference gate, OEM access, change and disable (mock bridge)")
